import { cpSync, existsSync, mkdirSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { buildDossier } from './vendor/makefun-app.ts';

const here = resolve(fileURLToPath(new URL('.', import.meta.url)));
const out = process.env.MAKEFUN_OUTPUT_DIR ?? '/output';

function log(msg: string) {
  console.log(`[build] ${msg}`);
}

function ensureDir(path: string) {
  mkdirSync(path, { recursive: true });
}

function copyTree(src: string, dest: string) {
  cpSync(src, dest, { recursive: true });
  log(`Copied ${src} -> ${dest}`);
}

log('Starting build for Neon Shore Cover Studio');
ensureDir(out);
log(`Output directory: ${out}`);

// Copy app directory (HTML, CSS, JS, fonts, samples)
log('Copying app/');
copyTree(join(here, 'app'), join(out, 'app'));

// Copy screenshots (generated by verify.mjs)
ensureDir(join(out, 'screenshots'));
if (existsSync(join(here, 'screenshots'))) {
  copyTree(join(here, 'screenshots'), join(out, 'screenshots'));
} else {
  log('No screenshots/ directory found, skipping');
}

const dossierPath = join(out, 'dossier.json');
log('Generating dossier.json');
const dossierBytes = buildDossier(out, {
  text_max_bytes: 163840,
  screenshots: { max: 4, max_bytes: 262144 },
  app_max_files: 993,
  app_max_bytes: 50331648,
  app_path_max_bytes: 1000,
});
writeFileSync(dossierPath, dossierBytes);
log(`Wrote dossier.json (${dossierBytes.length} bytes)`);
log('Build complete');